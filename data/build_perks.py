"""Pin vanilla skill-tree PERKs and generate the plugin's HasPerk registry.

Read AVIF nodes and NNAM rank links, not similarly named NPC/template perks.
Curated WoW translations are data/perk_rules.json; see docs/perks.md.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

from data.esm import read

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_ESM = Path(__file__).resolve().parents[2] / 'steamapps/common/Skyrim Special Edition/Data/Skyrim.esm'


def extract(path):
    records = read(path, {'PERK', 'AVIF'})
    perks = {r.form: r for r in records['PERK']}
    out = {}
    for tree in records['AVIF']:
        for node in tree.all('PNAM'):
            fid = struct.unpack('<I', node)[0]
            seen = set()
            while fid:
                if fid in seen:
                    raise ValueError('cyclic PERK rank chain')
                seen.add(fid)
                r = perks[fid]
                out[r.edid] = {'form': r.form, 'tree': tree.edid,
                               'source': [[t, v.hex()] for t, v in r.subs
                                          if t in ('PRKE', 'PRKC', 'DATA', 'CTDA', 'EPFT', 'EPFD', 'NNAM')]}
                fid = struct.unpack('<I', r.get('NNAM'))[0] if r.get('NNAM') else 0
    return dict(sorted(out.items()))


def registry(perks):
    return ('// Generated by python -m data.build_perks; vanilla AVIF nodes and PERK rank links.\n' +
            ''.join(f'{{ "{key}", 0x{row["form"]:08X} }},\n' for key, row in sorted(perks.items())))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--esm', type=Path, default=DEFAULT_ESM)
    ap.add_argument('--rules', type=Path, default=ROOT / 'data/perk_rules.json')
    ap.add_argument('--out', type=Path, default=ROOT / 'data/perks.json')
    ap.add_argument('--registry', type=Path, default=ROOT / 'skse/src/Perks.inc')
    a = ap.parse_args()
    config = json.loads(a.rules.read_text())
    perks = extract(a.esm)
    mapped = {key for rule in config['rules'] for key in rule['perks']}
    if mapped - perks.keys():
        raise ValueError(f'unknown vanilla perks: {sorted(mapped - perks.keys())}')
    dispositions = {key for group in config['dispositions'] for key in group['perks']}
    if mapped & dispositions or mapped | dispositions != perks.keys():
        raise ValueError('every vanilla tree perk needs exactly one mapped or native/no-analogue decision')
    data = {'schema': 1, 'provenance': {'esm': a.esm.name,
            'esm_sha256': hashlib.sha256(a.esm.read_bytes()).hexdigest(),
            'rules_sha256': hashlib.sha256(a.rules.read_bytes()).hexdigest()},
            'perks': perks, **config}
    a.out.write_text(json.dumps(data, indent=2, sort_keys=True) + '\n')
    a.registry.write_text(registry(perks))


if __name__ == '__main__':
    main()
