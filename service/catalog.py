"""Typed access to build/catalog.json (CMaNGOS spell_template rows + 1.12.1 DBC index tables)."""
import json
from pathlib import Path

DEFAULT = Path(__file__).resolve().parent.parent / 'build/catalog.json'


class Catalog:
    def __init__(self, path: Path = DEFAULT, *, raw: dict | None = None, armory: Path | bool = True):
        self.raw = json.loads(json.dumps(raw)) if raw is not None else json.loads(Path(path).read_text())
        self.poison_payloads = set(self.raw.get('poison_payloads', ()))
        # The pinned build catalog can predate talent code links. A deterministic
        # supplement is generated by the same builder, without rewriting build/.
        if raw is None and Path(path) == DEFAULT:
            extra = json.loads((DEFAULT.parent.parent / 'data/talent_catalog.json').read_text())
            for section in ('spells', 'cast_times', 'durations', 'ranges', 'radii', 'icons'):
                for key, row in extra[section].items():
                    self.raw[section].setdefault(key, row)
            for section in ('spell_affect', 'spell_proc_event', 'spell_facing'):
                for row in extra[section]:
                    if row not in self.raw[section]:
                        self.raw[section].append(row)
            extra = json.loads((DEFAULT.parent.parent / 'data/perk_catalog.json').read_text())
            for section in ('spells', 'cast_times', 'durations', 'ranges', 'icons'):
                for key, row in extra[section].items():
                    self.raw[section].setdefault(key, row)
            self.poison_payloads = set(extra['poison_payloads'])
        if armory is True and raw is None:   # beside the catalog it supplements
            armory = Path(path).resolve().parent / 'armory_catalog.json'
        # WoWBridgeArmory.esp's items (data/build_armory.py): their item_template rows (each without what its columns
        # default to), their sets and every spell they use, beside WoWBridge.esp's, which win.
        self.armory = set()   # the entries it adds
        if not isinstance(armory, bool) and Path(armory).exists():
            extra = json.loads(Path(armory).read_text())
            for section in ('spells', 'cast_times', 'durations', 'ranges', 'radii', 'icons', 'item_sets'):
                for key, row in extra[section].items():
                    self.raw.setdefault(section, {}).setdefault(key, row)
            for section in ('spell_affect', 'spell_proc_event', 'spell_facing'):
                known = {json.dumps(row, sort_keys=True) for row in self.raw.setdefault(section, [])}
                self.raw[section] += [row for row in extra[section] if json.dumps(row, sort_keys=True) not in known]
            for key, row in extra['items'].items():
                if key not in self.raw['items']:
                    self.raw['items'][key] = {**extra['item_defaults'], **row}
                    self.armory.add(int(key))
        self.spells = {int(k): v for k, v in self.raw['spells'].items()}
        # Imported equipment follows Skyrim requirements even with a stale catalog.
        # Progression's spell/item-book rank requirements are a separate data source.
        for item in self.raw['items'].values():
            item['RequiredLevel'] = 0
        self.items = {int(k): v for k, v in self.raw['items'].items()}
        self.item_use_spells = {item[f'spellid_{n}'] for item in self.items.values() for n in range(1, 6)
                               if item.get(f'spellid_{n}') and item.get(f'spelltrigger_{n}') == 0}
        self.slice = self.raw['slice']
        self.ranks = {int(k): v for k, v in self.raw.get('ranks', {}).items()}
        self.class_spells = sorted(set(self.ranks) | set(self.slice.values()))
        from service.skyrim_balance import rank_rules
        self.balance = rank_rules(self)
        self._affect = {(a['entry'], a['effectId']): a['SpellFamilyMask'] for a in self.raw['spell_affect']}
        self._facing = {int(f['entry']): int(f['facingcasterflag']) for f in self.raw.get('spell_facing', [])}

    def spell(self, spell_id: int) -> dict:
        return self.spells[int(spell_id)]

    def chain(self, spell_id: int) -> int:
        return self.ranks.get(spell_id, {}).get('chain', spell_id)

    def item(self, entry: int) -> dict | None:
        return self.items.get(int(entry))

    def creature(self, level: int) -> dict:
        """creature_template_classlevelstats (class 1) for a level, clamped to the table."""
        table = self.raw['creatures']
        levels = sorted(int(k) for k in table)
        level = min(max(int(level), levels[0]), levels[-1])
        return table.get(str(level)) or table[level]

    def creature_armor(self, level: int) -> int:
        return int(self.creature(level)['armor'])

    def creature_strength(self, level: int) -> int:
        return int(self.creature(level)['str'])

    def affect_mask(self, spell_id: int, eff_index0: int) -> int:
        """LoadSpellAffects propagates the first rank's SQL mask to higher ranks."""
        first = self.chain(spell_id)
        if (first, eff_index0) in self._affect:
            return int(self._affect[(first, eff_index0)])
        if (spell_id, eff_index0) in self._affect:
            return int(self._affect[(spell_id, eff_index0)])
        return int(self.spell(spell_id)[f'EffectItemType{eff_index0 + 1}'])

    def needs_facing(self, spell_id: int) -> bool:
        """SpellMgr::GetSpellFacingFlag & SPELL_FACING_FLAG_INFRONT (spell_facing): the target must be in front."""
        return bool(self._facing.get(int(spell_id), 0) & 1)

    def cast_time(self, s: dict) -> int:
        row = self.raw['cast_times'].get(str(s['CastingTimeIndex']))
        return row['Base'] if row else 0

    def duration(self, s: dict, level: int) -> int:
        """Spell duration with per-level growth capped at MaxDuration (SpellDuration.dbc)."""
        row = self.raw['durations'].get(str(s['DurationIndex']))
        if not row:
            return 0
        d = row['Duration'] + row['DurationPerLevel'] * level if row['DurationPerLevel'] else row['Duration']
        return min(d, row['MaxDuration']) if row['MaxDuration'] > 0 else d

    def range_yd(self, s: dict) -> tuple[float, float]:
        row = self.raw['ranges'][str(s['RangeIndex'])]
        return row['RangeMin'], row['RangeMax']

    def radius_yd(self, s: dict, eff: int) -> float:
        row = self.raw['radii'].get(str(s[f'EffectRadiusIndex{eff}']))
        return row['Radius'] if row else 0.0

    def icon(self, s: dict) -> str:
        row = self.raw['icons'].get(str(s['SpellIconID']))
        return row['TextureFilename'] if row else ''
